std::string valueName(Node* node)
{
    std::string name = "v_";
    for(char character : node->name)
    {
        name += std::isalnum(static_cast<unsigned char>(character)) ? character : '_';
    }
    return name;
}

std::string shapeLiteral(const std::vector<int>& shape)
{
    std::stringstream out;
    out << "(";
    for(size_t i = 0; i < shape.size(); ++i)
    {
        if(i) out << ", ";
        out << shape[i];
    }
    if(shape.size() == 1) out << ",";
    out << ")";
    return out.str();
}

std::string input(Node* node, size_t index)
{
    return index < node->inputs.size() ? valueName(node->inputs[index]) : "None";
}

